"""Which per-step host buffers FlashInfer's decode path pins, by vLLM release.

F046: vLLM 0.30.0 removed the deficit on Modal's driver 580.95.05 (F042), but
0.29.0 is at parity on GCP with the same driver (F044, F045), so the fix must
remove something the platform makes expensive. 0.30.0 pins host buffers that
FlashInfer's decode planning copies to the GPU with non_blocking=True. A
non-blocking copy from pageable memory is staged synchronously.

Reads the upstream files committed under results/external/vllm/ -- no network
-- and reports, for each release, whether each buffer is pinned, with the line
and the source comment as evidence.

    python analysis/vllm_pinning.py
"""
from __future__ import annotations
import hashlib, re, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXT = ROOT / "results" / "external" / "vllm"
OUT = ROOT / "analysis" / "out" / "tables"
TAGS = ("v0.29.0", "v0.30.0")

# Each probe: a buffer, how to find where it is pinned, and how to find it used.
PROBES = [
    ("paged_kv_indptr / last_page_len", re.compile(r"paged_kv_(indptr|last_page_len)_cpu\s*=\s*paged_kv_\w+_cpu\.pin_memory\(\)"),
     re.compile(r"paged_kv_(indptr|last_page_len)_cpu\s*=")),
    ("kv_lens for the decode plan", re.compile(r"kv_lens_decode_cpu\s*=\s*kv_lens_decode_cpu\.pin_memory\(\)"),
     re.compile(r"kv_lens_decode_cpu|seq_lens_cpu\s*=")),
    ("FlashInfer arange buffer (_get_range_buf)", re.compile(r"pin_host_range_buf\("),
     re.compile(r"_get_range_buf|pin_host_range_buf")),
]


def code_sha() -> str:
    try:
        return subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def main() -> int:
    src = {t: (EXT / t / "flashinfer.py").read_text().splitlines() for t in TAGS}
    L = ["# FlashInfer decode-path host buffers: pinned or pageable, by release", "",
         f"*Generated by `analysis/vllm_pinning.py` from `results/external/vllm/` at code "
         f"`{code_sha()}`. Do not edit by hand.*", "",
         "| tag | sha256 (first 16) |", "|---|---|"]
    for t in TAGS:
        L.append(f"| {t} | `{hashlib.sha256((EXT / t / 'flashinfer.py').read_bytes()).hexdigest()[:16]}` |")
    L += ["", "| buffer | " + " | ".join(TAGS) + " |", "|---|" + "---|" * len(TAGS)]
    detail = []
    for name, pin_rx, use_rx in PROBES:
        cells = []
        for t in TAGS:
            lines = src[t]
            pins = [i + 1 for i, l in enumerate(lines) if pin_rx.search(l)]
            uses = [i + 1 for i, l in enumerate(lines) if use_rx.search(l)]
            if pins:
                cells.append(f"pinned (l.{pins[0]})")
            elif uses:
                cells.append(f"**not pinned** (used l.{uses[0]})")
            else:
                cells.append("**no reference**")
            for i in pins[:1]:
                cmt = [lines[k].strip() for k in range(max(0, i - 4), i) if lines[k].strip().startswith("#")]
                if cmt:
                    detail.append(f"- {t}, {name}, l.{i}: `{' '.join(c.lstrip('# ') for c in cmt)[:160]}`")
        L.append(f"| {name} | " + " | ".join(cells) + " |")
    L += ["", "Source comments at the 0.30.0 pin sites:", ""] + detail
    L += ["", "A `non_blocking=True` host-to-device copy from pageable memory is staged "
          "synchronously. Where 0.30.0 pins and 0.29.0 does not, 0.29.0's decode step "
          "waits on that copy. This is the F046 candidate; it is not shown to cause the "
          "deficit, which needs a platform that still produces it to test."]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "vllm_pinning.md").write_text("\n".join(L) + "\n")
    print("  wrote analysis/out/tables/vllm_pinning.md")
    for l in L:
        if l.startswith("| ") and "buffer" not in l and "tag" not in l and "sha" not in l and "---" not in l:
            print("   ", l)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
