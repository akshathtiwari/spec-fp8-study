"""The GCP intervention sessions, one row per container: what ran, and the ratio.

F044 and F045 put Modal's deficit configuration on a plain GCP L4 under runc
and found parity. Modal then confirmed (support reply, 2026-11-03) that its GPU
Functions run under gVisor with nvproxy. The 2026-11-03 legs ran the same image
under upstream gVisor on one card, varying one thing at a time
(results/gcp/2026-11-03_gvisor_decision_rule.txt, pre-registered, with two
addenda committed before the legs they govern).

Records before the `sandbox` field are GCP runs under Docker's default runtime,
runc (cloud/gcp/host.sh before 2026-11-03 had no other), and are labelled so.

The interval is the conservative one used for F044: a t-interval on each arm's
mean, and the ratio of the opposite ends. It is wider than a bootstrap of the
ratio and assumes nothing about how the two arms covary.

    python analysis/sandbox_legs.py   # -> analysis/out/tables/sandbox_legs.md
"""
from __future__ import annotations

import json
import math
import statistics as st
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "analysis" / "out" / "tables" / "sandbox_legs.md"
T95 = {8: 2.365, 10: 2.262, 11: 2.228, 12: 2.201}


def sandbox(r: dict) -> str:
    return r.get("sandbox") or "runc"


def variant(r: dict) -> str:
    """The engine as built: F046=1 images carry vLLM 0.30.0's range-buffer pin."""
    eng = ((r.get("config") or {}).get("engine_ref") or "").replace("vllm-", "")
    return eng + (" + F046 pin" if (r.get("image") or "").endswith("-f046") else "")


def interval(d: list[float], e: list[float]) -> tuple[float, float]:
    def b(a):
        m, h = st.mean(a), T95.get(len(a), 2.2) * st.stdev(a) / math.sqrt(len(a))
        return m - h, m + h
    (dl, dh), (el, eh) = b(d), b(e)
    return dl / eh, dh / el


def rows() -> list[dict]:
    by: dict[str, dict] = {}
    for line in (ROOT / "results" / "probes.jsonl").open():
        if not line.strip():
            continue
        r = json.loads(line)
        if r.get("platform") != "gcp" or r.get("phase") != "boot_variance":
            continue
        if (r.get("load") or {}).get("concurrency") != 1:
            continue
        if (r.get("config") or {}).get("mechanism") != "dflash":
            continue
        env = r.get("env") or {}
        d = by.setdefault(r["probe_run"], {
            "session": r["probe_run"][:17], "sandbox": sandbox(r), "engine": variant(r),
            "driver": env.get("driver"), "card": (env.get("gpu_uuid") or "")[:12],
            "cpus": r.get("cpus_visible"), "omp": r.get("omp_num_threads"),
            "arms": defaultdict(list), "tau": defaultdict(list)})
        if r.get("arm") in ("default", "enforce_eager"):
            d["arms"][r["arm"]].append(r["throughput"]["output_tokens_per_s"])
            t = (r.get("spec") or {}).get("tau")
            if t:
                d["tau"][r["arm"]].append(t)
    out = []
    for d in by.values():
        a = d.pop("arms"); t = d.pop("tau")
        if not (a["default"] and a["enforce_eager"]):
            continue
        g, e = a["default"], a["enforce_eager"]
        lo, hi = interval(g, e)
        d.update(n=(len(g), len(e)), graph=st.mean(g), eager=st.mean(e),
                 graph_cv=st.stdev(g) / st.mean(g) * 100, eager_cv=st.stdev(e) / st.mean(e) * 100,
                 ratio=st.mean(g) / st.mean(e), lo=lo, hi=hi,
                 tau=st.mean(t["default"]) if t["default"] else None,
                 regime="deficit" if st.mean(g) / st.mean(e) < 0.95 else "parity")
        out.append(d)
    return sorted(out, key=lambda d: d["session"])


def main() -> None:
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                         capture_output=True, text=True).stdout.strip() or "unknown"
    R = rows()
    L = ["# GCP intervention sessions: container runtime, driver, engine", "",
         f"*Generated by `analysis/sandbox_legs.py` from `results/probes.jsonl` at code `{sha}`. "
         "Do not edit by hand.*", "",
         "DFlash, concurrency 1, fixed prompts, one container per row, NVIDIA L4. Ratio is "
         "default (CUDA graphs) over `--enforce-eager` throughput in the same container; "
         "the interval is conservative (ratio of opposite ends of each arm's t-interval). "
         "Records without a `sandbox` field ran under Docker's default runtime, runc.", "",
         "| session | runtime | driver | engine | card | cpus | OMP | graph tok/s (CV) | eager tok/s (CV) | ratio [95%] | regime |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in R:
        L.append(f"| {d['session']} | {d['sandbox']} | {d['driver']} | {d['engine']} | {d['card']} "
                 f"| {d['cpus']} | {d['omp'] or '-'} | {d['graph']:.1f} ({d['graph_cv']:.2f}%) "
                 f"| {d['eager']:.1f} ({d['eager_cv']:.2f}%) "
                 f"| **{d['ratio']:.3f}** [{d['lo']:.3f}, {d['hi']:.3f}] | {d['regime']} |")
    one = [d for d in R if d["session"].startswith("2026-11-03")]
    if one:
        cards = {d["card"] for d in one}
        g = [d for d in one if d["sandbox"].startswith("runsc")]
        rc = [d for d in one if d["sandbox"] == "runc"]
        L += ["", f"## The 2026-11-03 legs: one card ({', '.join(sorted(cards))}), six containers", ""]
        if rc and g:
            base = [d for d in g if d["engine"] == "0.29.0"]
            L.append(f"- Under runc, vLLM 0.29.0 is at **{rc[0]['ratio']:.3f}**. Under gVisor it is at "
                     + ", ".join(f"**{d['ratio']:.3f}** ({d['sandbox']}, driver {d['driver']})" for d in base)
                     + ": every gVisor build and driver tested.")
            for d in g:
                if d["engine"] != "0.29.0":
                    L.append(f"- Under {d['sandbox']}, driver {d['driver']}, **{d['engine']}** gives "
                             f"**{d['ratio']:.3f}** [{d['lo']:.3f}, {d['hi']:.3f}].")
            ge = [d["graph"] for d in base]; ee = [d["eager"] for d in base]
            L.append(f"- What gVisor costs vLLM 0.29.0 against runc: graph arm "
                     f"{(1 - st.mean(ge) / rc[0]['graph']) * 100:.0f}%, eager arm "
                     f"{(1 - st.mean(ee) / rc[0]['eager']) * 100:.0f}% (mean over the gVisor 0.29.0 legs).")
            L.append(f"- Graph-arm CV under gVisor: {min(d['graph_cv'] for d in g):.2f}--"
                     f"{max(d['graph_cv'] for d in g):.2f}%, against 3.73--13.92% in Modal's deficit "
                     "sessions. The ratio reproduces; the dispersion does not.")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"  wrote {OUT.relative_to(ROOT)} ({len(R)} sessions)")
    for d in R:
        print(f"  {d['session']}  {d['sandbox']:<17} {d['driver']}  {d['engine']:<16} "
              f"ratio {d['ratio']:.3f} [{d['lo']:.3f}, {d['hi']:.3f}]  graph CV {d['graph_cv']:.2f}%")


if __name__ == "__main__":
    main()
