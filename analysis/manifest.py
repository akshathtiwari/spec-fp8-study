"""Release manifest: what this repository contains, generated, never typed.

An external audit (3 Nov 2026) found the README's finding count drifting
from the archive's. Hand-maintained counts drift. This writes them from the
tree itself -- commit, version, DOIs, findings by kind, records and checksum
per raw file, engine logs -- so a reader can match a checkout to a Zenodo
version without trusting prose.

    python analysis/manifest.py
"""
from __future__ import annotations
import hashlib, json, re, subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "analysis" / "out" / "tables"


def git(*a: str) -> str:
    try:
        return subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True,
                              text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def main() -> int:
    cff = (ROOT / "CITATION.cff").read_text()
    version = (re.search(r"^version:\s*(\S+)", cff, re.M) or [None, "?"])[1]
    concept = (re.search(r"^doi:\s*(\S+)", cff, re.M) or [None, "?"])[1]
    kinds = Counter()
    for f in sorted((ROOT / "findings").glob("F0*.md")):
        m = re.search(r"^kind:\s*(\S+)", f.read_text(), re.M)
        kinds[m.group(1) if m else "?"] += 1
    raw = []
    for p in sorted((ROOT / "results").glob("*.jsonl")):
        b = p.read_bytes()
        raw.append((p.name, sum(1 for l in b.splitlines() if l.strip()),
                    hashlib.sha256(b).hexdigest()))
    logs = len(list((ROOT / "results" / "logs").glob("*.log")))
    L = ["# Release manifest", "",
         f"*Generated by `analysis/manifest.py` at code `{git('rev-parse', '--short', 'HEAD')}`. "
         "Do not edit by hand.*", "",
         "| | |", "|---|---|",
         f"| version (CITATION.cff) | {version} |",
         f"| concept DOI | {concept} (resolves to the newest version) |",
         f"| last release tag | {git('describe', '--tags', '--abbrev=0')} |",
         f"| commits since that tag | {git('rev-list', '--count', git('describe', '--tags', '--abbrev=0') + '..HEAD')} |",
         f"| findings | {sum(kinds.values())} ({', '.join(f'{v} {k}' for k, v in sorted(kinds.items()))}) |",
         f"| engine logs | {logs} |", "",
         "| raw file | records | sha256 |", "|---|---|---|"]
    L += [f"| results/{n} | {c} | `{h}` |" for n, c, h in raw]
    L += ["", "Commits after the last tag are not in any Zenodo version until the next "
          "release; the concept DOI's newest version is the last tag."]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "manifest.md").write_text("\n".join(L) + "\n")
    print(f"  wrote analysis/out/tables/manifest.md: {sum(kinds.values())} findings, "
          f"{sum(c for _, c, _ in raw)} records, {logs} logs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
